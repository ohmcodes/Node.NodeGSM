'use strict';
// Windows background start for the web mode ("unattended"): a Task Scheduler task that starts the headless web server (src/server/headless.js,
// run by the same Electron binary in Node mode) without the desktop window, so the web UI is up after a reboot with nobody signed in.
//   boot   task "At Windows start" as SYSTEM (needs an elevated NodeGSM / administrator once to create it; runs with nobody signed in)
//   logon  task "At sign-in" for the current user (no administrator needed; starts when that user signs in)
// Why a scheduled task and not an installed service: a real Windows service needs a wrapper executable (WinSW / NSSM / node-windows) that
// NodeGSM would have to ship and sign; the task gives the same "starts at boot, hidden, restarts on failure" result with built-in Windows tools.
// The desktop app and this background server must not run on the same data folder at the same time: stop one of them.
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const TASK_NAME = 'NodeGSM Web';

/** PowerShell single-quoted literal. */
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

/**
 * Text of the small PowerShell launcher the task runs: sets ELECTRON_RUN_AS_NODE, starts headless.js with the web settings, appends
 * the output to <data>\logs\service.log and starts again after 30 s if it ever exits (a crash).
 * o: { exe, script, dataDir, host, port, https, trustProxy, require2fa }
 */
function buildLauncher(o) {
  const args = ['--host', String(o.host || '127.0.0.1'), '--port', String(Number(o.port) || 8730), '--data', o.dataDir];
  if (o.https) args.push('--https');
  if (o.trustProxy) args.push('--trust-proxy');
  if (o.require2fa) args.push('--require-2fa');
  const log = path.join(o.dataDir, 'logs', 'service.log');
  return [
    '# Generated by NodeGSM (Settings > Web access > Background start). Safe to delete together with the task "' + TASK_NAME + '".',
    '$ErrorActionPreference = "Continue"',
    '$env:ELECTRON_RUN_AS_NODE = "1"',
    `New-Item -ItemType Directory -Force -Path ${q(path.dirname(log))} | Out-Null`,
    'while ($true) {',
    `  & ${q(o.exe)} ${q(o.script)} ${args.map(q).join(' ')} *>> ${q(log)}`,
    '  Start-Sleep -Seconds 30',
    '}',
    '',
  ].join('\r\n');
}

/** schtasks arguments that create the task. mode: 'boot' | 'logon'. */
function createArgs(mode, launcherPath) {
  const tr = `powershell.exe -NoProfile -NonInteractive -WindowStyle Hidden -ExecutionPolicy Bypass -File "${launcherPath}"`;
  const base = ['/Create', '/TN', TASK_NAME, '/TR', tr, '/F'];
  return mode === 'boot' ? [...base, '/SC', 'ONSTART', '/RU', 'SYSTEM', '/RL', 'HIGHEST'] : [...base, '/SC', 'ONLOGON', '/RL', 'LIMITED'];
}

const sch = (args) => { const r = spawnSync('schtasks.exe', args, { encoding: 'utf8', windowsHide: true }); return { code: r.status, out: String(r.stdout || '') + String(r.stderr || ''), error: r.error }; };

/** Parse `schtasks /Query /FO LIST /V`. */
function parseStatus(out) {
  const get = (re) => { const m = re.exec(out); return m ? m[1].trim() : ''; };
  const status = get(/^\s*Status:\s*(.+)$/im);
  return { installed: true, running: /running/i.test(status), status, mode: /At system start/i.test(out) ? 'boot' : /At log ?on/i.test(out) ? 'logon' : '', lastResult: get(/^\s*Last Result:\s*(.+)$/im) };
}

function status() {
  if (process.platform !== 'win32') return { supported: false, installed: false, running: false };
  const r = sch(['/Query', '/TN', TASK_NAME, '/FO', 'LIST', '/V']);
  if (r.code !== 0) return { supported: true, installed: false, running: false };
  return { supported: true, ...parseStatus(r.out) };
}

/** Create the launcher + the task and start it. o: see buildLauncher, plus mode. Returns status(); throws a readable error. */
function install(o) {
  if (process.platform !== 'win32') throw new Error('The background task is for Windows. On Linux use deploy/nodegsm.service (see docs/GUIDE-web-linux.md).');
  const mode = o.mode === 'boot' ? 'boot' : 'logon';
  const dir = path.join(o.dataDir, 'service'); fs.mkdirSync(dir, { recursive: true });
  const launcher = path.join(dir, 'nodegsm-web.ps1');
  fs.writeFileSync(launcher, buildLauncher(o), 'utf8');
  const r = sch(createArgs(mode, launcher));
  if (r.code !== 0) {
    if (/access is denied|zugriff/i.test(r.out)) throw new Error(mode === 'boot' ? 'Windows refused: creating a task that runs at system start needs administrator rights. Start NodeGSM with "Run as administrator" once, or choose "At sign-in".' : 'Windows refused to create the task: ' + r.out.trim());
    throw new Error('Could not create the task: ' + r.out.trim().split(/\r?\n/).pop());
  }
  sch(['/Run', '/TN', TASK_NAME]);
  return status();
}

function uninstall() {
  if (process.platform !== 'win32') throw new Error('The background task is for Windows.');
  sch(['/End', '/TN', TASK_NAME]);
  const r = sch(['/Delete', '/TN', TASK_NAME, '/F']);
  if (r.code !== 0 && !/cannot find|not exist|nicht gefunden/i.test(r.out)) throw new Error('Could not remove the task: ' + r.out.trim().split(/\r?\n/).pop());
  return status();
}

module.exports = { TASK_NAME, buildLauncher, createArgs, parseStatus, status, install, uninstall };
